// ٤٠١ · «الرقمُ العربيُّ يجرّ صيغةَ معدودِه»
//
// دالّةُ تمييزٍ واحدةٌ لكلّ نصٍّ يعرض عدداً بوحدة (ثانية · دقيقة · ساعة
// · يوم…). القاعدةُ التي يعرفها القارئُ العربيّ العاديّ، بأربع خانات:
//
//   ١  → مفرد  (ثانيةٌ · دقيقةٌ · ساعةٌ)
//   ٢  → مثنّى (ثانيتان/ثانيتين · دقيقتان/دقيقتين · ساعتان/ساعتين)
//   ٣–١٠ → جمعُ القلّة (ثوانٍ · دقائق · ساعات)
//   ١١+ (و ٠) → مفردُ التمييز (ثانية · دقيقة · ساعة)
//
// **لماذا هنا لا في `apps/studio/src/format/`:** الاشتقاقُ لغويّ لا
// عرضيّ — يُشارَك بين مكوّنات (`RenderPendingAlert`)، مُنسّقات
// (`formatRelative`)، ومستقبَلات (dashboard إذا نُقل). القيمُ العرضيّةُ
// نفسُها (نصوصُ «ثانية»/«ثوانٍ»…) تعيش في `ar.json`/`mixed.json` تحت
// المفاتيح المُنسَّخة الأربعة، فتبقى فصلاً بين البنية والنصّ.
//
// **CLDR:** التصنيفُ الكامل CLDR للعربيّة يميّز `many` (11–99) عن
// `other` (100+). قلَّصنا هنا إلى `other` لأنّ الصيغةَ في المعدود
// (ثانية · دقيقة · ساعة) واحدةٌ في الحالتين. لو أُضيفت وحدةٌ يختلف
// معدودُها بينهما (نادر) فسِّع التصنيف حينَها لا الآن (L-27).

export type ArPluralCategory = 'one' | 'two' | 'few' | 'other';

/** يعيد فئةَ التمييز حسب قاعدة العربيّة العاديّة. سالبٌ يُعامَل قيمةً
 *  مطلقةً (–3 دقائق ≡ 3 دقائق في التمييز). كسورٌ تُقصّ إلى صحيح. */
export function arPluralCategory(n: number): ArPluralCategory {
  const abs = Math.abs(Math.trunc(n));
  if (abs === 1) return 'one';
  if (abs === 2) return 'two';
  if (abs >= 3 && abs <= 10) return 'few';
  return 'other';
}

/** يختار من كائنٍ رباعيٍّ بالفئات — قصيرٌ ومباشر. الحقولُ الأربعة
 *  إلزاميّةٌ حتى لا يُنسى بعضُها زمنَ التحرير. */
export function pluralFor(
  n: number,
  forms: Readonly<Record<ArPluralCategory, string>>,
): string {
  return forms[arPluralCategory(n)];
}
