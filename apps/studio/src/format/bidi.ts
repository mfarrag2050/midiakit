// LRM/RLM — علامات اتجاه غير مرئية لضبط ترتيب النصّ في سياقات
// weak-bidi (أرقام داخل عربية، رموز، إلخ).
//
// **متى تُستعمل:**
// - `LRM` بعد رقم لاتيني ينتهي جملة عربية كي لا تتّبع الأحرف اللاحقة
//   اتجاه الرقم.
// - `RLM` قبل نصّ عربي يتبع رقماً لاتينياً كي لا يظهر معكوساً.
//
// **بديل أنظف للمركّبات:** استعمل مكوّن `<Ltr>` لعزل السياق بدل حَقن
// علامات كلما استطعت — العلامات لا تُرى فتصعب تشخيصها.
//
// **شاهد L-23:** «460.4 / 108.0 GB» يُقرأ معكوساً بلا عزل — الحلّ
// الموصى به: <Ltr>460.4 / 108.0 GB</Ltr>. العلامات هنا للحالات
// النادرة التي لا يمكن فيها إضافة عنصر.

export const LRM = '‎';
export const RLM = '‏';

/** يُدرج LRM بعد كل رقم لاتيني يتبعه حرف عربي مباشرة داخل نصّ حرّ. */
export function isolateLatinNumbersInArabic(s: string): string {
  return s.replace(/([0-9])([؀-ۿ])/g, `$1${LRM}$2`);
}

/** يُدرج RLM قبل بادئة عربية تلي رقماً — عكس الحالة السابقة. */
export function isolateArabicAfterNumber(s: string): string {
  return s.replace(/([0-9])([؀-ۿ])/g, `$1${RLM}$2`);
}
