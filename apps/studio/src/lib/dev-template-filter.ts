// 330-THREE-LEAKS-AND-A-LIE §3.1 · فلترة القوالب المسمّاة بلغة المطوّر.
//
// **السياق:** بعض القوالب على mkapi (مثل «بسيط — إثبات بوّابة المرحلة ٢»)
// تحمل اسماً وُلد أثناء التطوير لإثبات بوّابة معماريّة. لا يفيد اسمها
// عميلاً. الأداة لا تستطيع تعديل بيانات mkapi، لكنّها تُخفي هذه القوالب من
// كلّ قائمة عرضٍ للاختيار حتّى تُنظَّف قواعد البيانات — أو يُقلَب علمٌ.
//
// **يُطبَّق على:**
//   - `/templates` — قائمة التصفح (page.tsx)
//   - `/projects` — dropdown اختيار القالب عند الإنشاء
//
// **لا يُطبَّق على:**
//   - `/exports` — البحث عن اسم قالبٍ لتصديرٍ سابق (تاريخ لا اختيار).
//     إن كان مشروعٌ قديمٌ قائماً على قالبٍ دِيفلبريّ الاسم فسنعرض اسمه كي
//     لا يفقد العميل السياق.
//
// الأنماط أدناه تُغطّي الحالات المُشاهَدة اليوم. إن ظهر نمطٌ جديد أضِفه
// هنا — نقطة تعديل واحدة.
const DEV_NAME_PATTERNS: readonly RegExp[] = [
  /إثبات\s*(?:بوّابة|بوابة)/,   // «إثبات بوّابة المرحلة ٢»
  /المرحلة\s*[٠-٩0-9]/,          // «المرحلة 2»
  /\bmock\b/i,
  /\bdev\b/i,
  /\bseed\b/i,
];

export function isDevNamedTemplate(name: string): boolean {
  return DEV_NAME_PATTERNS.some((p) => p.test(name));
}
